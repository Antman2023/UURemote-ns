#include "protocol.hpp"
#include <iostream>
#include <random>
#include <stdexcept>
using namespace uu;
void check(bool ok, const char *message) {
    if (!ok)
        throw std::runtime_error(message);
}
template <class F> void rejects(F f) {
    bool rejected = false;
    try {
        f();
    } catch (const std::exception &) {
        rejected = true;
    }
    check(rejected, "Expected rejection");
}
std::string hex(const Bytes &b) {
    std::string out;
    for (auto c : b) {
        out += "0123456789abcdef"[c >> 4];
        out += "0123456789abcdef"[c & 15];
    }
    return out;
}
int main() {
    try {
        // Golden vectors generated by the already-validated reference Web implementation.
        auto headers =
            requestHeaders("test-key", "POST", "/api/test", "{}", "client", "device", "user", 123456789);
        check(headers.at("X-Param-SIGN") ==
                  "bde127df49e8d93a661a4b2e524aee17475dca99bd3de74c3341bf7755c930b7",
              "HMAC differs from Web client");
        check(hex(connectOptions()) == "080110ffffffffffffffffff011a1808011003180120022a0608800a10d0053206088"
                                       "00a10d005220a081e100118800a20d0054002",
              "ConnectOptions differs from Web client");
        auto message = soac("pc", "candidate", {{"candidate", "candidate:1"}, {"sdpMid", "0"}}, 7, "control");
        check(message["data"]["candidate"]["candidate"] == "candidate:1" && message["data"]["ice_id"] == 7,
              "Nested ICE envelope");
        check(signalingUrl("signal.nrd.nie.163.com") ==
                  "wss://signal.nrd.nie.163.com/socket.io/?EIO=4&transport=websocket",
              "Signal URL");
        rejects([] { signalingUrl("wss://163.com.attacker.org"); });
        rejects([] { signalingUrl("ws://signal.nie.163.com"); });
        rejects([] { signalingUrl("wss://attacker@nie.163.com"); });
        check(ackValue(Json::array({nullptr, {{"ice_id", 3}}}), "control")["ice_id"] == 3, "Native ACK");
        check(ackValue(Json::array({{{"publisher", "pc"}}}), "room")["publisher"] == "pc",
              "Single object ACK");
        rejects([] { ackValue(Json::array({"denied", Json::object()}), "control"); });
        auto p = parseSocketIo("461-23[null,{\"ice_id\":4}]");
        check(p.type == 6 && p.attachments == 1 && p.id == 23, "Binary ACK parsing");
        check(parseSocketIo("42[\"left\",{}]").data[0] == "left", "Event parsing");
        rejects([] { parseSocketIo("4516x[]"); });
        rejects([] { parseSocketIo("45-"); });
        rejects([] { parseSocketIo("42/other,[]"); });
        auto frame = wsFrame(2, {1, 2, 3, 4}, {10, 20, 30, 40});
        check(frame == Bytes({0x82, 0x84, 10, 20, 30, 40, 11, 22, 29, 44}), "Client masking");
        WsParser parser;
        Bytes fragmented{0x01, 2, 'h', 'e', 0x89, 1, 'p', 0x80, 3, 'l', 'l', 'o'};
        std::vector<WsMessage> messages;
        for (auto byte : fragmented) {
            auto part = parser.feed(&byte, 1);
            messages.insert(messages.end(), part.begin(), part.end());
        }
        check(messages.size() == 2 && messages[0].opcode == 9 &&
                  messages[1].data == Bytes({'h', 'e', 'l', 'l', 'o'}),
              "Fragmentation and interleaved ping");
        rejects([] {
            WsParser p;
            Bytes b{0x82, 0xff, 0x80, 0, 0, 0, 0, 0, 0, 0};
            p.feed(b.data(), b.size());
        });
        rejects([] {
            WsParser p;
            Bytes b{0x89, 126, 0, 126};
            p.feed(b.data(), b.size());
        });
        rejects([] {
            WsParser p;
            Bytes b{0x80, 0};
            p.feed(b.data(), b.size());
        });
        // Randomized framing lengths, chunk boundaries, and payloads exercise stream parsing.
        std::mt19937 random(17);
        for (int run = 0; run < 300; ++run) {
            size_t size = run < 3 ? size_t(125 + run) : random() % 12000;
            Bytes raw(size);
            for (auto &b : raw)
                b = uint8_t(random());
            Bytes wire{0x82};
            if (size < 126)
                wire.push_back(size);
            else {
                wire.push_back(126);
                wire.push_back(size >> 8);
                wire.push_back(size);
            }
            wire.insert(wire.end(), raw.begin(), raw.end());
            WsParser p;
            std::vector<WsMessage> out;
            for (size_t offset = 0; offset < wire.size();) {
                size_t n = std::min(wire.size() - offset, size_t(1 + random() % 127));
                auto part = p.feed(wire.data() + offset, n);
                out.insert(out.end(), part.begin(), part.end());
                offset += n;
            }
            check(out.size() == 1 && out[0].data == raw, "Randomized WebSocket stream");
        }
        auto id = uuid();
        check(id.size() == 36 && id[14] == '4' && std::string("89ab").find(id[19]) != std::string::npos,
              "UUID version and variant");
        std::cout << "Protocol tests passed (golden signatures, protobuf, ICE, Socket.IO, 300 WebSocket "
                     "streams).\n";
    } catch (const std::exception &e) {
        std::cerr << e.what() << '\n';
        return 1;
    }
    return 0;
}
